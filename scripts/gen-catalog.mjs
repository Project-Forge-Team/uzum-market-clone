const esc = (s) =>
  String(s)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");

function svgFor(product, categoryName, variant) {
  const [from, to] = product.palette;
  const angle =
    variant === 0 ? `x1="0" y1="0" x2="1" y2="1"` : variant === 1 ? `x1="0" y1="1" x2="1" y2="0"` : `x1="0.2" y1="0" x2="0.8" y2="1"`;

  const glyphSize = variant === 2 ? 330 : 190;
  const glyphY = variant === 2 ? 470 : 400;
  const showText = variant !== 2;
  const blob =
    variant === 1
      ? `<circle cx="620" cy="180" r="210" fill="#ffffff" opacity="0.45"/><circle cx="180" cy="640" r="150" fill="${to}" opacity="0.9"/>`
      : variant === 2
        ? `<rect x="80" y="120" width="640" height="120" rx="60" fill="#ffffff" opacity="0.35"/>`
        : `<circle cx="400" cy="380" r="230" fill="#ffffff" opacity="0.55"/>`;

  return `<svg xmlns="http://www.w3.org/2000/svg" width="800" height="800" viewBox="0 0 800 800" role="img" aria-label="${esc(product.title)}">
  <defs><linearGradient id="g" ${angle}><stop offset="0" stop-color="${from}"/><stop offset="1" stop-color="${to}"/></linearGradient></defs>
  <rect width="800" height="800" rx="40" fill="url(#g)"/>
  ${blob}
  <text x="400" y="${glyphY}" font-size="${glyphSize}" text-anchor="middle" font-family="'Segoe UI Emoji','Apple Color Emoji','Noto Color Emoji',sans-serif">${esc(product.emoji)}</text>
  ${
    showText
      ? `<text x="400" y="660" font-size="42" font-weight="600" text-anchor="middle" fill="#1F1F1F" font-family="system-ui,-apple-system,'Segoe UI',Roboto,sans-serif">${esc(product.title.length > 34 ? product.title.slice(0, 33) + "…" : product.title)}</text>
  <text x="400" y="706" font-size="26" text-anchor="middle" fill="#1F1F1F" opacity="0.55" font-family="system-ui,-apple-system,'Segoe UI',Roboto,sans-serif">${esc(categoryName)}${variant > 0 ? " · вид " + (variant + 1) : ""}</text>`
      : ""
  }
  <rect x="40" y="40" width="150" height="46" rx="23" fill="#ffffff" opacity="0.75"/>
  <text x="115" y="71" font-size="22" text-anchor="middle" fill="#7000FF" font-family="system-ui,-apple-system,'Segoe UI',Roboto,sans-serif">DEMO PHOTO</text>
</svg>
`;
}

