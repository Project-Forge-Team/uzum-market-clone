const catBySlug = new Map(CATEGORIES.map((c) => [c.slug, c]));
const sellerBySlug = new Map(SELLERS.map((s) => [s.slug, s]));

// Товары, для которых в public/products уже лежат настоящие PNG-фото.
const PRODUCTS_REAL_PHOTOS = new Set([
  "gaming-set",
  "keyboard",
  "laptop-stand",
  "mouse-pink",
  "phone-holder",
  "polo-white",
]);

const products = [];
let nextId = 1;

for (const p of PRODUCTS) {
  const category = catBySlug.get(p.cat);
  const seller = sellerBySlug.get(p.seller);
  if (!category) throw new Error(`Нет категории ${p.cat} (товар ${p.slug})`);
  if (!seller) throw new Error(`Нет продавца ${p.seller} (товар ${p.slug})`);

  const files = [];
  for (let v = 0; v < 3; v += 1) {
    const file = v === 0 ? `${p.slug}.svg` : `${p.slug}-${v + 1}.svg`;
    writeFileSync(join(IMG_DIR, file), svgFor(p, category.name, v), "utf8");
    files.push(`/products/gen/${file}`);
  }

  // Для шести товаров, которые уже есть в реальных PNG-фото, главное фото — настоящее.
  const localPng = `/products/${p.slug}.png`;
  const hasRealPhoto = PRODUCTS_REAL_PHOTOS.has(p.slug);
  const image = hasRealPhoto ? localPng : files[0];
  const images = hasRealPhoto ? [localPng, ...files] : files;

  products.push({
    id: nextId++,
    slug: p.slug,
    title: p.title,
    description: p.description,
    price: p.price,
    old_price: p.old > 0 ? p.old : null,
    stock: p.stock,
    brand: seller.name.split(" ")[0],
    delivery_time: p.delivery,
    characteristics: p.specs,
    image,
    images,
    category_slug: p.cat,
    seller_slug: p.seller,
    is_ad: p.old > 0 && p.price > 900000,
    views: 80 + ((nextId * 37) % 1900),
  });
}

const reviews = [];
let reviewId = 1;
products.forEach((product, index) => {
  // Детерминированно раздаём 1..3 отзыва на товар (без Math.random — база воспроизводима)
  const count = 1 + ((index * 7) % 3);
  for (let i = 0; i < count; i += 1) {
    const poolItem = REVIEW_POOL[(index * 3 + i) % REVIEW_POOL.length];
    const dayShift = (index * 5 + i * 11) % 240;
    reviews.push({
      id: reviewId++,
      product_id: product.id,
      author: REVIEW_AUTHORS[(index + i * 4) % REVIEW_AUTHORS.length],
      rating: poolItem.rating,
      text: poolItem.text,
      created_at: new Date(
        Date.parse("2026-08-20T10:00:00.000Z") - dayShift * 86_400_000,
      ).toISOString(),
      verified: (index + i) % 3 !== 0,
      seller_reply:
        (index + i) % 9 === 0
          ? "Спасибо за отзыв! Если появятся вопросы по эксплуатации — напишите в чат магазина, поможем."
          : null,
    });
  }
});

